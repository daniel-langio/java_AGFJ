package vendredi.soir.agfj.core.physics;

/**
 * Represent a vector in a 2D space
 * */
public class Vector2D extends Coordinate2d {

    /**
     * Creates a vector object
     *
     * @param x the value of the x-axis.
     * @param y the value of the y-axis.
     * */
    public Vector2D(double x, double y) {super(x, y);}
}
